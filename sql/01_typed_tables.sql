-- Types were decided from a full scan of the staging data, not assumed:
--   * exactly four columns contain only bare integers (transactionid, isfraud,
--     transactiondt, card1) -- they get integer types;
--   * every other numeric column is float-formatted in the raw CSV
--     (card2 is "321.0", not "321"), so a direct ::int would fail;
--     they get double precision;
--   * transactionamt gets numeric (exact) because it is money;
--   * columns with any non-numeric value stay text;
--   * no quoted-empty-string values ('' vs NULL) exist in either file,
